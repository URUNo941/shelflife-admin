const router = require("express").Router();
const c = require("../controllers/inventoryController");
router.use(require("../middleware/requireAuth"));
router.get("/", c.getInventoryItems);
router.get("/item/:itemId", c.getInventoryItem);
router.get("/:userId", c.getInventoryItems);
router.post("/", c.createInventoryItem);
router.patch("/:itemId", c.updateInventoryItem);
router.put("/:itemId", c.updateInventoryItem);
router.delete("/:itemId", c.deleteInventoryItem);
module.exports = router;
